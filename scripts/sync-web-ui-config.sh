#!/bin/bash
# =============================================================================
# Sync Web UI Config from Devnet Addresses
# =============================================================================
# Reads addresses from .devnet/addresses.json and scripts/config/optimism-addresses.json
# and updates web-ui/src/config.ts accordingly.
#
# Usage:
#   ./scripts/sync-web-ui-config.sh
# =============================================================================

set -eo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

DEVNET_ADDRESSES="$PROJECT_ROOT/.devnet/addresses.json"
OPTIMISM_ADDRESSES="$PROJECT_ROOT/scripts/config/optimism-addresses.json"
CONFIG_TS="$PROJECT_ROOT/web-ui/src/config.ts"

echo -e "${CYAN}╔════════════════════════════════════════════════════════════╗${NC}"
echo -e "${CYAN}║  Sync Web UI Config from Devnet Addresses                 ║${NC}"
echo -e "${CYAN}╚════════════════════════════════════════════════════════════╝${NC}"
echo ""

# Check required files
if [ ! -f "$DEVNET_ADDRESSES" ]; then
    echo -e "${RED}Error: .devnet/addresses.json not found${NC}"
    echo "Run ./scripts/generate-optimism-allocs-sepolia.sh first"
    exit 1
fi

if [ ! -f "$OPTIMISM_ADDRESSES" ]; then
    echo -e "${RED}Error: scripts/config/optimism-addresses.json not found${NC}"
    echo "Run ./scripts/generate-optimism-allocs-sepolia.sh first"
    exit 1
fi

if [ ! -f "$CONFIG_TS" ]; then
    echo -e "${RED}Error: web-ui/src/config.ts not found${NC}"
    exit 1
fi

# Read addresses from .devnet/addresses.json (TON Staking V3)
TON=$(jq -r '.ton' "$DEVNET_ADDRESSES")
