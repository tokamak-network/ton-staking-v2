SEIG_MANAGER=$(jq -r '.seigManagerProxy' "$DEVNET_ADDRESSES")
DEPOSIT_MANAGER=$(jq -r '.depositManagerProxy' "$DEVNET_ADDRESSES")
LAYER2_MANAGER=$(jq -r '.layer2ManagerProxy' "$DEVNET_ADDRESSES")
L1_BRIDGE_REGISTRY=$(jq -r '.l1BridgeRegistryProxy' "$DEVNET_ADDRESSES")
LAYER2_REGISTRY=$(jq -r '.layer2RegistryProxy' "$DEVNET_ADDRESSES")
RAT=$(jq -r '.ratProxy' "$DEVNET_ADDRESSES")
VALIDATOR_REWARD=$(jq -r '.validatorRewardProxy' "$DEVNET_ADDRESSES")

# Read addresses from scripts/config/optimism-addresses.json (Optimism Stack)
SYSTEM_CONFIG=$(jq -r '.SystemConfigProxy' "$OPTIMISM_ADDRESSES")
DISPUTE_GAME_FACTORY=$(jq -r '.DisputeGameFactoryProxy' "$OPTIMISM_ADDRESSES")

echo -e "${YELLOW}Addresses to sync:${NC}"
echo "  TON:                 $TON"
echo "  WTON:                $WTON"
echo "  SeigManager:         $SEIG_MANAGER"
echo "  DepositManager:      $DEPOSIT_MANAGER"
echo "  Layer2Manager:       $LAYER2_MANAGER"
echo "  L1BridgeRegistry:    $L1_BRIDGE_REGISTRY"
echo "  Layer2Registry:      $LAYER2_REGISTRY"
echo "  RAT:                 $RAT"
echo "  ValidatorReward:     $VALIDATOR_REWARD"
